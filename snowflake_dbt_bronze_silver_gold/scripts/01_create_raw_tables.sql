-- Illustrative raw tables. Add source filename, batch_id, ingestion_ts and source_system
-- in your real ingestion contract. These tables are not used by the seed demo by default.
CREATE TABLE IF NOT EXISTS DBT_DEMO.RAW.CUSTOMERS (
  CUSTOMER_ID VARCHAR,
  CUSTOMER_NAME VARCHAR,
  COUNTRY VARCHAR,
  UPDATED_AT TIMESTAMP_NTZ,
  SOURCE_SYSTEM VARCHAR DEFAULT 'IRIS',
  SOURCE_FILE VARCHAR,
  BATCH_ID VARCHAR,
  INGESTION_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS DBT_DEMO.RAW.PRODUCTS (
  PRODUCT_ID VARCHAR,
  PRODUCT_NAME VARCHAR,
  PRODUCT_CATEGORY VARCHAR,
  STANDARD_COST NUMBER(12,2),
  SOURCE_SYSTEM VARCHAR DEFAULT 'FINANCE_FOUNDATION',
  SOURCE_FILE VARCHAR,
  BATCH_ID VARCHAR,
  INGESTION_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS DBT_DEMO.RAW.SALES (
  SALE_ID VARCHAR,
  CUSTOMER_ID VARCHAR,
  PRODUCT_ID VARCHAR,
  SALE_DATE VARCHAR,
  QUANTITY VARCHAR,
  UNIT_PRICE VARCHAR,
  DISCOUNT_AMOUNT VARCHAR,
  CURRENCY_CODE VARCHAR,
  UPDATED_AT VARCHAR,
  SOURCE_SYSTEM VARCHAR DEFAULT 'APPLICATION',
  SOURCE_FILE VARCHAR,
  BATCH_ID VARCHAR,
  INGESTION_TS TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
